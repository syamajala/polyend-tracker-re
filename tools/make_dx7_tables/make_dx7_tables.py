#!/usr/bin/env python3
"""Generate modules/dx7/src/dx7_tables.cpp (DX7 engine lookup tables).

The tables follow the integer recipes of Google's Music Synthesizer for
Android (msfa, Apache 2.0: sin.cc, exp2.cc, freqlut.cc), computed here
offline so they live in flash instead of 20 KB of SRAM filled at boot. The
sine table is the exception: it is read from SRAM, so initSinTable() builds it
there at boot from two constants, with the same integer steps as sin_table()
(#122: no 4 KB flash copy of it).
The frequency table depends on the audio sample rate (kSampleRate,
audio_tables.h). Usage: make_dx7_tables.py > modules/dx7/src/dx7_tables.cpp
"""
import math

SAMPLE_RATE = 44117.647  # audio/audio_tables.h kSampleRate (MCLK / 256)
LG_N = 10
N = 1 << LG_N


def sin_steps():
    # cos / sin of one table step, Q30: the only floating point in Sin::init.
    dphase = 2 * math.pi / N
    return (int(math.floor(math.cos(dphase) * (1 << 30) + 0.5)),
            int(math.floor(math.sin(dphase) * (1 << 30) + 0.5)))


def sin_table():
    # msfa Sin::init (values in Q24), plain form: N + 1 entries. initSinTable()
    # in the generated file runs the same steps.
    R = 1 << 29
    c, s = sin_steps()
    u, v = 1 << 30, 0
    tab = [0] * (N + 1)
    for i in range(N // 2):
        tab[i] = (v + 32) >> 6
        tab[i + N // 2] = -((v + 32) >> 6)
        t = (u * s + v * c + R) >> 30
        u = (u * c - v * s + R) >> 30
        v = t
    tab[N] = 0
    return tab


def exp2_table():
    inc = 2.0 ** (1.0 / N)
    y = float(1 << 30)
    tab = [0] * (N + 1)
    for i in range(N):
        tab[i] = int(math.floor(y + 0.5))
        y *= inc
    tab[N] = 1 << 31   # 2^31 wraps to INT32_MIN: lookups use the unsigned difference
    return tab


def freq_table():
    y = float(1 << (24 + 20)) / SAMPLE_RATE
    inc = 2.0 ** (1.0 / N)
    tab = []
    for _ in range(N + 1):
        tab.append(int(math.floor(y + 0.5)))
        y *= inc
    return tab


def emit(name, tab, const=True, ctype="int32_t"):
    out = [f"{'const ' if const else ''}{ctype} {name}[{len(tab)}] = {{"]
    for i in range(0, len(tab), 8):
        out.append("    " + ", ".join(str(x) for x in tab[i:i + 8]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    print("// GENERATED by tools/make_dx7_tables/make_dx7_tables.py -- do not edit.")
    print("//")
    print("// DX7 engine lookup tables (audio/engines/dx7.cpp): the integer recipes of")
    print("// msfa's sin.cc / exp2.cc / freqlut.cc (Copyright 2012 Google Inc., Apache")
    print("// License 2.0, third_party/LICENSES/msfa.txt), precomputed into flash.")
    print(f"// kDx7FreqLut is for a {SAMPLE_RATE} Hz sample rate.")
    print('#include "dx7_tables.h"')
    print()
    print("namespace ot {")
    print("namespace audio {")
    print("namespace dx7 {")
    print()
    c, s = sin_steps()
    print("// Sine, Q24, one cycle + the wrap entry. In SRAM (.bss), read 6 x 128")
    print("// times per voice per block; built at boot by initSinTable() (msfa")
    print("// Sin::init: a rotation by one step per entry, integer only, ~60 us).")
    print("int32_t gDx7Sin[kTabN + 1];")
    print()
    print("void initSinTable() {")
    print("    if (gDx7Sin[kTabN / 4]) return;   // built: sin(pi / 2) = 1 << 24")
    print(f"    constexpr int64_t kCos = {c}, kSin = {s}, kRound = 1 << 29;   // one step, Q30")
    print("    int32_t u = 1 << 30, v = 0;")
    print("    for (int i = 0; i < kTabN / 2; ++i) {")
    print("        gDx7Sin[i] = (v + 32) >> 6;")
    print("        gDx7Sin[i + kTabN / 2] = -((v + 32) >> 6);")
    print("        const int32_t t = int32_t((int64_t(u) * kSin + int64_t(v) * kCos + kRound) >> 30);")
    print("        u = int32_t((int64_t(u) * kCos - int64_t(v) * kSin + kRound) >> 30);")
    print("        v = t;")
    print("    }")
    print("    gDx7Sin[kTabN] = 0;")
    print("}")
    print()
    print("// 2^x mantissa, Q30 (unsigned: the last entry is 2^31).")
    print(emit("kDx7Exp2", [x & 0xffffffff for x in exp2_table()], ctype="uint32_t"))
    print()
    print("// Phase increment (Q24 per sample << 20) of 2^(i / 1024) octaves.")
    print(emit("kDx7FreqLut", freq_table()))
    print()
    print("}  // namespace dx7")
    print("}  // namespace audio")
    print("}  // namespace ot")


if __name__ == "__main__":
    main()
